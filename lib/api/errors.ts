const concurrencyCodes = new Set([
  "teaching_concurrent_change",
  "room_concurrent_change",
  "subject_concurrent_change",
  "class_registration_concurrent_change",
  "student_request_concurrent_change",
]);

export function isConcurrencyCode(code: string | undefined) {
  return Boolean(code && concurrencyCodes.has(code));
}
